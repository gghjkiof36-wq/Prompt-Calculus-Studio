// Rebuild the checked-in classic content script with the pinned development tool.
import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

export const ESBUILD_VERSION = '0.25.12';
const root = fileURLToPath(new URL('../', import.meta.url));
export const outputPath = path.join(root, 'extensions/chrome/content.js');

export async function bundleContent(modulePath = process.env.ESBUILD_MODULE) {
  const require = createRequire(new URL('./chrome-content/package.json', import.meta.url));
  const esbuild = await import(pathToFileURL(modulePath ? path.resolve(modulePath) : require.resolve('esbuild')).href);
  if (esbuild.version !== ESBUILD_VERSION) throw new Error(`Expected esbuild ${ESBUILD_VERSION}; received ${esbuild.version}`);
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['extensions/chrome/entry.js'],
    outfile: 'extensions/chrome/content.js',
    bundle: true, write: false, metafile: true,
    platform: 'browser', target: ['chrome116'], format: 'iife',
    charset: 'utf8', minify: false, sourcemap: false, legalComments: 'none',
    banner: {js: `// Generated by tools/build_chrome_content.mjs with esbuild ${ESBUILD_VERSION}. Edit the source modules, then rebuild.`},
    logLevel: 'silent',
  });
  const output = result.outputFiles[0];
  const imports = Object.values(result.metafile.outputs).flatMap(item => item.imports);
  if (result.outputFiles.length !== 1 || imports.length) throw new Error('Content bundle must be one file without runtime imports');
  return {code: output.text, inputs: Object.keys(result.metafile.inputs).sort()};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node tools/build_chrome_content.mjs [--check]');
  const {code} = await bundleContent();
  if (process.argv.includes('--check')) {
    if (await readFile(outputPath, 'utf8') !== code) throw new Error('content.js differs from its sources; rebuild before packaging');
    process.stdout.write('Chrome content bundle matches its sources.\n');
  } else {
    await writeFile(outputPath, code, 'utf8');
    process.stdout.write('Built extensions/chrome/content.js.\n');
  }
}
