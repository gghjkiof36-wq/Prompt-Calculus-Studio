import json
import os
from pathlib import Path
from types import SimpleNamespace as NS
import unittest
import uuid
from unittest.mock import Mock, patch

from PySide6.QtCore import QPointF, QPoint, QUrl
from prompt_calculus_studio import prompt_materials, snapshot_history
from prompt_calculus_studio.dialogs import SettingsDialog
from prompt_calculus_studio.workflow_manager import WorkflowManager
from prompt_calculus_studio.settings_page import WorkflowSettings
from prompt_calculus_studio.snapshots import make_snapshot
import test_workspace_shell as fixture
from test_multi_output import workflow


FIXTURE = Path(__file__).with_name('fixtures') / 'document_write_routes_8e9e87e.json'


class DocumentWriteRouteTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls): fixture.WorkspaceShellTests.setUpClass()

    def test_each_handler_keeps_body_undo_and_refresh(self):
        capture = os.environ.get('PCS_WRITE_CAPTURE')
        serial = itertools.count(1)
        result = {}
        expected = {} if capture else json.loads(FIXTURE.read_text(encoding='utf-8'))
        with patch('uuid.uuid4', side_effect=lambda: uuid.UUID(bytes=hashlib.sha256(str(next(serial)).encode()).digest()[:16])), \
             patch('time.time', return_value=1700000000.), \
             patch.object(prompt_materials, 'RUNTIME_FIELDS', tuple(sorted(prompt_materials.RUNTIME_FIELDS))):
            f = fixture.WorkspaceShellTests()
            f.setUp()
            try:
                tab = f.w.open_path(f.root / 'Street.pcs-workflow')
                f.events()
                host = f.w.ensure_utility()
                host.state = copy.deepcopy(tab.host.state)
                f.w.open_route('home')
                canvas = host.canvas
                host.canvas.refresh()
                base = copy.deepcopy(host.state)
                key = next(iter(base['multi_output']['canvases']))
                output = base['multi_output']['current_output']
                errors = []
                host.error = errors.append
                notices = []
                host.notice = notices.append
                events = []
                if not capture:
                    host.documentChanged.connect(lambda fields, reason, kind: events.append((fields, reason, kind)))

                def reset():
                    host.changes.stop(); host.save_timer.stop()
                    host.state = copy.deepcopy(base)
                    canvas.undo_stack.clear(); canvas.redo_stack.clear(); canvas.last_state = None
                    canvas.refresh(); host.generation_panel.refresh()
                    host.changes.stop(); host.save_timer.stop()
                    errors.clear(); events.clear(); notices.clear()

                def record(ident, action, reason, fields, kind='content', setup=None):
                    nonlocal serial
                    reset()
                    serial = itertools.count(1000)
                    if setup: setup()
                    host.changes.stop(); host.save_timer.stop(); events.clear()
                    before_undo = copy.deepcopy(canvas.undo_stack)
                    before_redo = copy.deepcopy(canvas.redo_stack)
                    counts = {}
                    with ExitStack() as stack:
                        for obj, name, label in (
                            (host,'changed','changed'), (host,'refresh_workspaces','workspaces'),
                            (host,'refresh_modules','modules'), (host,'refresh_library','library'),
                            (host,'refresh_builder','builder'), (canvas,'refresh','canvas'),
                            (canvas,'sync','sync'), (canvas,'update_output','output'),
                            (host.generation_panel,'changed','generation_changed'),
                            (host.generation_panel,'refresh','generation_refresh')):
                            original = getattr(obj, name)
                            def counted(*args, _original=original, _label=label, **kwargs):
                                counts[_label] = counts.get(_label,0)+1
                                return _original(*args, **kwargs)
                            stack.enter_context(patch.object(obj, name, counted))
                        update = stack.enter_context(patch.object(host, 'update_document', wraps=host.update_document)) if not capture else None
                        adopt = stack.enter_context(patch.object(host, 'adopt_document', wraps=host.adopt_document)) if not capture else None
                        action()
                    self.assertEqual(errors, [], ident)
                    if not capture:
                        matching = [e for e in events if e[1] == reason]
                        self.assertTrue(matching, (ident, events))
                        self.assertEqual(matching[-1], (fields if fields == 'ALL' else frozenset(fields), reason, kind))
                        calls = (adopt if fields == 'ALL' else update).call_args_list
                        self.assertTrue(any(call.kwargs.get('reason') == reason for call in calls), (ident, calls))
                    # Save outside the measured handler, exactly as in the old
                    # UI. Compare the SQLite TEXT verbatim, not re-serialized.
                    host.store.save(host.state)
                    row = dict(before_undo=before_undo, before_redo=before_redo,
                        undo=copy.deepcopy(canvas.undo_stack), redo=copy.deepcopy(canvas.redo_stack),
                        refresh=counts, body=host.store.db.execute('SELECT body FROM document WHERE id=1').fetchone()[0])
                    row = json.loads(json.dumps(row, ensure_ascii=False))
                    result[ident] = row
                    if not capture:
                        with self.subTest(path=ident):
                            for field in row:
                                self.assertEqual(row[field], expected[ident][field], ident+'/'+field)
                    host.changes.stop(); host.save_timer.stop()

                def dictionary():
                    dialog = SettingsDialog(host)
                    try:
                        dialog.dictionary.setPlainText('新詞 = new word')
                        dialog.save(False)
                    finally: dialog.deleteLater()
                record('UI-022', dictionary, 'dictionary', {'dictionary'})

                def edit(): canvas.commit(lambda s: s['uses'][next(iter(s['uses']))].update(prompt='changed'), label='probe')
                record('UI-062-undo', canvas.undo, 'canvas-undo', 'ALL', setup=edit)
                record('UI-062-redo', canvas.redo, 'canvas-redo', 'ALL', setup=lambda: (edit(),canvas.undo()))

                def restore():
                    record = {'metadata': {'raw': {'prompt_studio': {'schema_version':1,
                        'bindings':[{'node_id':'2','snapshot':make_snapshot(host.state)}]}}}}
                    with patch('prompt_calculus_studio.pages.ask',return_value=True): host.gallery.restore_combination(record)
                record('UI-067', restore, 'snapshot-import', 'ALL')
                record('UI-074', canvas.undo, 'snapshot-undo', 'ALL', setup=restore)
                record('UI-074-redo', canvas.redo, 'snapshot-redo', 'ALL', setup=lambda: (restore(),canvas.undo()))

                def profile(): host.generation_panel.save_profile(workflow())
                record('profile', profile, 'workflow-profile', {'generation'})
                manager = WorkflowManager(host)
                manager.selected = lambda: next(iter(host.state.get('generation',{}).get('profiles',[])), None)
                manager.entry = lambda: {'kind':'local','id':'flow','name':'Workflow','path':''}
                def rename():
                    with patch('prompt_calculus_studio.workflow_manager.InputDialog.getText', return_value=('Renamed',True)):
                        manager.rename()
                record('rename', rename, 'workflow-rename', {'generation'}, setup=profile)

                transfer = dict(format='prompt_studio_workflow',version=1,id='flow',name='Imported',graph=workflow()['graph'],bindings=[])
                transfer_path = f.root / 'transfer.json'
                transfer_path.write_text(json.dumps(transfer),encoding='utf-8')
                record('workflow-import', lambda: host.generation_panel.import_workflow(transfer_path), 'workflow-import','ALL')
                def reimport():
                    with patch('prompt_calculus_studio.workflow_manager.QFileDialog.getOpenFileName', return_value=(str(transfer_path),'')):
                        manager.reimport()
                record('UI-112', reimport, 'workflow-reimport', 'ALL', setup=profile)
                host.state['settings']['skip_workflow_delete_confirmation'] = True
                record('UI-113', lambda: manager.finish_remove('flow'), 'workflow-remove', 'ALL', setup=profile)
                record('UI-114', manager.undo_remove, 'workflow-restore', 'ALL', setup=lambda: (profile(),manager.finish_remove('flow')))
                def drop():
                    event = NS(mimeData=lambda: NS(urls=lambda:[QUrl.fromLocalFile(str(transfer_path))]),acceptProposedAction=Mock())
                    WorkflowSettings.dropEvent(NS(window=host),event)
                    event.acceptProposedAction.assert_called_once()
                record('workflow-drop', drop, 'workflow-import', 'ALL')

                data_path = f.root / 'data.json'
                data_path.write_text(json.dumps(base,ensure_ascii=False),encoding='utf-8')
                def import_json():
                    with patch('prompt_calculus_studio.window.QFileDialog.getOpenFileName',return_value=(str(data_path),'')), \
                         patch('prompt_calculus_studio.window.ask',return_value=True):
                        host.import_json()
                record('UI-111', import_json, 'json-import','ALL',setup=edit)

                # Settings/imports belong to the utility host; canvas routes
                # use the visible document host, as Start.cmd does.
                host.changes.stop(); host.save_timer.stop()
                host = tab.host
                canvas = host.canvas
                host.state['settings']['reduce_motion'] = True
                f.w.open_route('home'); host.enter_canvas(); f.events()
                base = copy.deepcopy(host.state)
                key = next(iter(base['multi_output']['canvases']))
                output = base['multi_output']['current_output']
                host.error = errors.append; host.notice = notices.append
                if not capture:
                    host.documentChanged.connect(lambda fields, reason, kind: events.append((fields, reason, kind)))
                record('N01', host.persist, 'save-synchronize', {'multi_output','workspace_scenes'},'derived',setup=edit)
                def ratio():
                    page = canvas.outputs[output].panel.open_page()
                    try:
                        editor = page.content
                        editor.split.setSizes([270,500])
                        editor.split.splitterMoved.emit(editor.split.sizes()[0],1)
                    finally: page.finish()
                record('N02', ratio, 'output-panel-ratio', {'multi_output'},'view')
                new_output = []
                record('N03', lambda: canvas.set_current(new_output[0]), 'current-output',
                       {'multi_output','draft','draft_base','selections','weights','instances','temporary','temporary_before'},
                       setup=lambda: new_output.append(canvas.add_output(QPointF(1300,100))))
                def view():
                    canvas.open_editor(key)
                    editor = canvas.editor_page
                    editor.view_ready = True
                    editor.view.scale(1.1,1.1)
                    editor.save_view()
                    editor.close_editor()
                record('N04', view, 'canvas-edit-view', {'multi_output'},'view')
                def out_of_bounds():
                    member = canvas.data()['canvases'][key]['members'][0]
                    host.state['text_positions'][member] = [-9000,-9000]
                    canvas.cards[member].setPos(-9000,-9000)
                record('N05', canvas.refresh_layout, 'canvas-bounds', {'multi_output','text_positions'},'derived',setup=out_of_bounds)
                def outdated(): host.state['multi_output']['outputs'][output]['list_state'] = {}
                record('N06', canvas.update_output, 'output-projection', {'multi_output'},'derived',setup=outdated)
                record('A01', lambda: snapshot_history.capture(canvas), 'snapshot-capture', {'workspace_scenes'},'derived')
                from prompt_calculus_studio import workspace_scene
                destination = []
                def another_workspace():
                    destination[:] = [workspace_scene.create(host.state,'Another')]
                record('N07', lambda: host.change_workspace(destination[0]), 'workspace-switch',
                    set(workspace_scene.FIELDS) | {'workspace','workspace_scenes','generation','_execution_inputs'}, setup=another_workspace)
                record('N08', lambda: host.activate_prompt_view('canvas'), 'selection-view',
                    {'multi_output','selection_view','draft','draft_base','view_drafts'},'view',
                    setup=lambda: host.state.update(selection_view='list'))
                manager.deleteLater()
                if capture:
                    Path(capture).write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
                else:
                    self.assertEqual(set(result), set(expected))
                type(self).route_ids = list(result)
            finally:
                f.tearDown()

    def test_model_menu_keeps_other_actions_in_order(self):
        from prompt_calculus_studio.pages import ModelPage
        texts = []
        class Menu:
            def __init__(self,*a): pass
            def addAction(self,text,callback): texts.append(text)
            add_destructive_action = addAction
            def addSeparator(self): texts.append('<separator>')
            def open_at(self,*a): pass
        item = object()
        page = NS(list=NS(itemAt=lambda pos:item,setCurrentItem=Mock(),viewport=lambda:NS(mapToGlobal=lambda p:p)),
                  window=NS(copy_text=Mock()),trigger=NS(toPlainText=lambda:'trigger'),choose_image=Mock(),reveal=Mock(),recycle=Mock())
        with patch('prompt_calculus_studio.pages.QMenu',Menu): ModelPage.context(page,QPoint())
        self.assertEqual(texts,['複製觸發詞','設定預覽圖','顯示檔案位置','<separator>','移至資源回收筒…'])


if __name__ == '__main__': unittest.main()
